using Woad.Core.Commands;
using Woad.Core.Content;
using Woad.Core.Events;
using Woad.Core.Grid;
using Woad.Core.Model;
using Woad.Core.Rules;
using Woad.Core.Tests.Support;

namespace Woad.Core.Tests.Rules;

public class FloorTests
{
    private const string Empty = """
        .........
        .........
        .........
        .........
        .........
        .........
        .........
        .........
        .........
        """;

    /// <summary>Floor 1: the hero stands next to the stairs. Floor 2: an arrival room.</summary>
    private static RoomSetup[] TwoFloors(string upstairs) =>
    [
        new RoomSetup("up", TestRun.Room(upstairs), Floor: 1, Role: RoomRole.Stairs),
        new RoomSetup("down", TestRun.Room("""
            .........
            .........
            .........
            ..1...2..
            .........
            .........
            .........
            .........
            .........
            """), Floor: 2, Role: RoomRole.Arrival),
    ];

    private const string StairsBeside = """
        .........
        .........
        .........
        .........
        ...1>....
        .........
        .........
        .........
        .........
        """;

    [Fact]
    public void StairsLeadToTheNextFloorsArrivalRoom()
    {
        GameSession session = TestRun.Start(TwoFloors(StairsBeside), new ScriptedDice(3));
        Hero hero = session.HeroInSeat();
        session.Do(new RollMovement(hero.Id));

        Assert.Contains("on the stairs", session.Refuse(new TakeStairs(hero.Id)));
        session.Do(new MoveHero(hero.Id, new GridPosition(4, 4)));
        var descended = session.Do(new TakeStairs(hero.Id)).SingleOf<HeroDescended>();

        Assert.Equal(new HeroDescended(hero.Id, "up", "down", 2, new GridPosition(2, 3), FirstTimeOnFloor: true), descended);
        Assert.Equal("down", hero.RoomId);
        Assert.True(session.RoomById("down").Explored);
        Assert.Equal(3, session.State.Turn!.MovementPoints);
    }

    [Fact]
    public void ReachingANewFloorRestoresLuckAndCharges()
    {
        GameSession session = TestRun.Start(TwoFloors(StairsBeside), new ScriptedDice(3), stats: GameRules.HeroBaseStats with { Luck = 2 }, cards: ["wand"]);
        Hero hero = session.HeroInSeat();
        hero.LuckRemaining = 0;
        hero.Card("wand").ChargesRemaining = 0;

        session.Do(new RollMovement(hero.Id));
        session.Do(new MoveHero(hero.Id, new GridPosition(4, 4)));
        session.Do(new TakeStairs(hero.Id));

        Assert.Equal(2, hero.LuckRemaining);
        Assert.Equal(2, hero.Card("wand").ChargesRemaining);
        Assert.Equal(2, hero.DeepestFloor);
        Assert.Equal(GameRules.XpPerNewFloor, hero.Xp);
    }

    [Fact]
    public void TheExitOpensOnceTheBossFalls()
    {
        GameSession session = TestRun.Start("""
            .........
            .........
            .........
            .........
            ...1*....
            .........
            .........
            .........
            W........
            """, new ScriptedDice(3), cards: ["coin"]);
        Hero hero = session.HeroInSeat();
        session.Do(new RollMovement(hero.Id));
        session.Do(new MoveHero(hero.Id, new GridPosition(4, 4)));

        Assert.Contains("sealed until the boss", session.Refuse(new Escape(hero.Id)));

        session.RoomById().RemoveMonster(session.OnlyMonster());
        IReadOnlyList<GameEvent> events = session.Do(new Escape(hero.Id));

        Assert.Equal(new HeroEscaped(hero.Id, 5), events[0]);
        Assert.Equal(HeroStatus.Escaped, hero.Status);
        Assert.Equal([hero.Id], Assert.IsType<RunEnded>(events[^1]).WinnerHeroIds);
        Assert.Equal([hero.Id], session.State.WinnerIds);
    }

    [Fact]
    public void EscapingEndsYourTurnAndPlayContinues()
    {
        GameSession session = TestRun.Start("""
            .........
            .........
            .........
            ....*....
            ...1.2...
            .........
            .........
            .........
            .........
            """, new ScriptedDice(3), heroes: 2);
        Hero first = session.HeroInSeat(0);
        session.Do(new RollMovement(first.Id));
        session.Do(new MoveHero(first.Id, new GridPosition(4, 3)));

        IReadOnlyList<GameEvent> events = session.Do(new Escape(first.Id));

        Assert.Equal(new TurnStarted(session.HeroInSeat(1).Id), events[^1]);
        Assert.Equal(RunPhase.InProgress, session.State.Phase);
    }

    [Fact]
    public void ClearingARoomRestoresAHeart()
    {
        GameSession session = TestRun.Start("""
            .........
            .........
            .........
            ....m....
            ....1....
            .........
            .........
            .........
            .........
            """, new ScriptedDice(5, 1));
        Hero hero = session.HeroInSeat();
        hero.Hearts = 2;

        IReadOnlyList<GameEvent> events = session.Do(new AttackMonster(hero.Id, session.OnlyMonster().Id));

        Assert.Equal(new HeroHealed(hero.Id, GameRules.HeartsOnRoomClear, 2 + GameRules.HeartsOnRoomClear), events[^1]);
        Assert.IsType<RoomCleared>(events[^2]);
    }

    [Fact]
    public void TrapRoomsStaySealedUntilCleared()
    {
        RoomSetup[] rooms =
        [
            new("trap", TestRun.Room("""
                .........
                .........
                .........
                .........
                ......m1.
                .........
                .........
                .........
                .........
                """), new Dictionary<Direction, string> { [Direction.East] = "next" }, Trap: true),
            new("next", TestRun.Room(Empty), new Dictionary<Direction, string> { [Direction.West] = "trap" }),
        ];
        GameSession session = TestRun.Start(rooms, new ScriptedDice(3, 5, 1));
        Hero hero = session.HeroInSeat();
        session.Do(new RollMovement(hero.Id));
        session.Do(new MoveHero(hero.Id, Direction.East.DoorTile()));

        Assert.True(session.RoomById("trap").IsSealed);
        Assert.Empty(session.GetUsableDoors());
        Assert.Contains("sealed", session.Refuse(new GoThroughDoor(hero.Id, Direction.East)));

        session.Do(new MoveHero(hero.Id, new GridPosition(7, 4)));
        IReadOnlyList<GameEvent> events = session.Do(new AttackMonster(hero.Id, session.OnlyMonster("trap").Id));

        Assert.Equal(new RoomCleared("trap"), events[^1]);
        Assert.False(session.RoomById("trap").IsSealed);
    }
}
