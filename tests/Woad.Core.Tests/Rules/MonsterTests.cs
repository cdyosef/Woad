    [Fact]
    public void MonstersInRoomsWithoutHeroesStayPaused()
    {
        RoomSetup[] rooms =
        [
            new("A", TestRun.Room("""
                .........
                .........
                .........
                .........
                .......1.
                .........
                .........
                .........
                .........
                """), new Dictionary<Direction, string> { [Direction.East] = "B" }),
            new("B", TestRun.Room("""
                .........
                .........
                .........
                .........
                ..m......
                .........
                .........
                .........
                .........
                """), new Dictionary<Direction, string> { [Direction.West] = "A" }),
        ];
        GameSession session = TestRun.Start(rooms, new ScriptedDice(1, 1, 1));
        Hero hero = session.HeroInSeat();

        Assert.DoesNotContain(session.EndRound(), gameEvent => gameEvent is MonsterMoved);

        session.Do(new RollMovement(hero.Id));
        session.Do(new MoveHero(hero.Id, Direction.East.DoorTile()));
        session.Do(new GoThroughDoor(hero.Id, Direction.East));
        IReadOnlyList<GameEvent> events = session.EndRound();

        Assert.Equal([new GridPosition(1, 4)], events.SingleOf<MonsterMoved>().Path);
        Assert.Single(events.OfType<AttackRolled>());
    }

    [Fact]
    public void DownedHeroesDropWhatTheyFoundAndKeepWhatTheyBroughtIn()
    {
        GameSession session = TestRun.Start("""
            .........
            .........
            .........
            ....m....
            ....1....
            .........
            .........
            .........
            .........
            """, new ScriptedDice(5, 1), cards: ["sword"]);
        Hero hero = session.HeroInSeat();
        var gem = new CardInstance(session.State.NextId(), TestContent.Catalog.GetCard("gem"), broughtInByHeroId: null);
        hero.AddToBackpack(gem);
        hero.Hearts = 1;

        IReadOnlyList<GameEvent> events = session.EndRound();

        Assert.Equal(new HeroDowned(hero.Id, new GridPosition(4, 4), [gem.Id]).HeroId, events.SingleOf<HeroDowned>().HeroId);
        Assert.Equal([gem.Id], events.SingleOf<HeroDowned>().DroppedCardIds);
        Assert.Equal(HeroStatus.Downed, hero.Status);
        Assert.Equal(["sword"], hero.AllCards.Select(card => card.Definition.Id));
        Assert.Equal([gem], session.RoomById().LootAt(new GridPosition(4, 4)));
    }

    [Fact]
    public void TheRunEndsWhenNobodyIsLeftAndNobodyEscaped()
    {
        GameSession session = TestRun.Start("""
            .........
            .........
            .........
            ....m....
            ....1....
            .........
            .........
            .........
            .........
            """, new ScriptedDice(5, 1));
        session.HeroInSeat().Hearts = 1;

        Assert.Equal(new RunEnded([]).WinnerHeroIds, Assert.IsType<RunEnded>(session.EndRound()[^1]).WinnerHeroIds);
        Assert.Equal(RunPhase.Ended, session.State.Phase);
        Assert.Null(session.State.Turn);
        Assert.Empty(session.State.WinnerIds);
        Assert.Contains("isn't in progress", session.Refuse(new EndTurn(session.HeroInSeat().Id)));
    }

