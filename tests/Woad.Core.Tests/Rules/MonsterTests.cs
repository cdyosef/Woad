    [Fact]
    public void FlyersCrossPitsThatStopEveryoneElse()
    {
        const string room = """
            ....X....
            .........
            ~~~~~~~~~
            .........
            ....1....
            .........
            .........
            .........
            .........
            """;

        GameSession flying = TestRun.Start(room.Replace('X', 'f'), new ScriptedDice(1, 1));
        Assert.Equal(
            [new GridPosition(4, 1), new GridPosition(4, 2), new GridPosition(4, 3)],
            flying.EndRound().SingleOf<MonsterMoved>().Path);

        GameSession walking = TestRun.Start(room.Replace('X', 'm'));
        Assert.Equal([new GridPosition(4, 1)], walking.EndRound().SingleOf<MonsterMoved>().Path);
    }

    [Fact]
    public void ErraticMonstersStillMoveOneTileAtATime()
    {
        GameSession session = TestRun.Start("""
            b........
            .........
            .........
            .........
            .........
            .........
            .........
            .........
            ........1
            """);

        IReadOnlyList<GridPosition> path = session.EndRound().SingleOf<MonsterMoved>().Path;

        Assert.InRange(path.Count, 1, 4);
        Assert.Equal(1, new GridPosition(0, 0).ManhattanDistanceTo(path[0]));
        for (int i = 1; i < path.Count; i++)
        {
            Assert.Equal(1, path[i - 1].ManhattanDistanceTo(path[i]));
        }
    }

    [Fact]
    public void BossesSweepEveryHeroNearbyEveryOtherTurn()
    {
        GameSession session = TestRun.Start("""
            .........
            .........
            ....1....
            .........
            ....W....
            .........
            ......2..
            .........
            3........
            """, new ScriptedDice(5, 1, 1), heroes: 3);

        Assert.DoesNotContain(session.EndRound(), gameEvent => gameEvent is AttackRolled);

