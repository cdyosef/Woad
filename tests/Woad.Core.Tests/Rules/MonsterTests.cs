    [Fact]
    public void MonstersCloseInAndAttack()
    {
        GameSession session = TestRun.Start("""
            .........
            ....m....
            .........
            .........
            ....1....
            .........
            .........
            .........
            .........
            """, new ScriptedDice(5, 4));
        Hero hero = session.HeroInSeat();
        Monster grunt = session.OnlyMonster();

        IReadOnlyList<GameEvent> events = session.EndRound();

        Assert.Equal([new GridPosition(4, 2), new GridPosition(4, 3)], events.SingleOf<MonsterMoved>().Path);
        Assert.Equal(grunt.Id, events.SingleOf<AttackRolled>().AttackerId);
        Assert.Equal(new Damaged(hero.Id, 1, 3), events.SingleOf<Damaged>());
        Assert.Equal(3, hero.Hearts);
    }

